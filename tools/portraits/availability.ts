/**
 * `tsx tools/portraits/availability.ts`: writes src/portraits/options.ts and src/portraits/availability.ts from
 * public/portraits/manifest.json and palettes.json, so the engine (which cannot load the manifest) knows which
 * options each age stage and body type offers. src/portraits/availability.test.ts fails when the files are stale.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const assets = path.join(root, 'public', 'portraits');

interface Template {
  age: string;
  sex: string;
  hairstyles: Record<string, unknown>;
  outfits: Record<string, unknown>;
  facial_hair: Record<string, unknown>;
}
interface Option {
  id: string;
}
interface Manifest {
  revision: number;
  age_order: string[];
  templates: Template[];
  hairstyles: Option[];
  outfits: Option[];
  brow_styles: Option[];
  eye_shapes: Option[];
  lash_styles: Option[];
  nose_shapes: Option[];
  facial_hair_styles: Option[];
  hat_styles: Option[];
  accessory_options: { eyewear: Option[]; earrings: Option[] };
}
interface Palettes {
  skin: { id: string }[];
  hair: { id: string }[];
  eyes: { id: string }[];
  clothing: { id: string }[];
  hats: { id: string }[];
}

export async function buildTables(): Promise<{ options: string; availability: string }> {
  const manifest = JSON.parse(await readFile(path.join(assets, 'manifest.json'), 'utf8')) as Manifest;
  const palettes = JSON.parse(await readFile(path.join(assets, 'palettes.json'), 'utf8')) as Palettes;
  const list = (ids: string[]) => `[${ids.map((i) => `'${i}'`).join(', ')}] as const`;
  const ids = (p: { id: string }[]) => p.map((x) => x.id);
  const options = `// Generated by tools/portraits/availability.ts from the portrait manifest (revision ${manifest.revision}). Do not edit.
export const ASSET_REVISION = ${manifest.revision};
export const HAIRSTYLES = ${list(['original', ...manifest.hairstyles.map((x) => x.id)])};
export const OUTFITS = ${list(['original', ...manifest.outfits.map((x) => x.id)])};
export const EYE_SHAPES = ${list(['original', ...manifest.eye_shapes.map((x) => x.id)])};
export const BROW_STYLES = ${list(['original', ...manifest.brow_styles.map((x) => x.id)])};
export const LASH_STYLES = ${list(manifest.lash_styles.map((x) => x.id))};
export const NOSE_SHAPES = ${list(['original', ...manifest.nose_shapes.map((x) => x.id)])};
export const FACIAL_HAIR = ${list(manifest.facial_hair_styles.map((x) => x.id))};
export const HATS = ${list(manifest.hat_styles.map((x) => x.id))};
export const EYEWEAR = ${list(manifest.accessory_options.eyewear.map((x) => x.id))};
export const EARRINGS = ${list(manifest.accessory_options.earrings.map((x) => x.id))};
export const AGE_STAGES = ${list(manifest.age_order)};
export const SKIN_TONES = ${list(ids(palettes.skin))};
export const NATURAL_HAIR_COLORS = ${list(ids(palettes.hair).filter((id) => id !== 'silver'))};
export const HAIR_COLORS = ${list(ids(palettes.hair))};
export const EYE_COLORS = ${list(ids(palettes.eyes))};
export const CLOTHING_COLORS = ${list(ids(palettes.clothing))};
export const HAT_COLORS = ${list(ids(palettes.hats))};
`;
  const rows: string[] = [];
  for (const age of manifest.age_order) {
    const male = manifest.templates.find((t) => t.age === age && t.sex === 'male')!;
    const female = manifest.templates.find((t) => t.age === age && t.sex === 'female')!;
    const q = (o: object) => `[${Object.keys(o).map((i) => `'${i}'`).join(', ')}]`;
    rows.push(`  ${age}: { hairstyles: { male: ${q(male.hairstyles)}, female: ${q(female.hairstyles)} }, outfits: ${q(male.outfits)}, facialHair: ${q(male.facial_hair)} },`);
  }
  const availability = `// Generated by tools/portraits/availability.ts from the portrait manifest (revision ${manifest.revision}). Do not edit.
import type { AgeStage } from './ids';

/** What each age stage offers, for generation. The renderer still normalizes every portrait (normalizeAppearance). */
export const STAGE_OPTIONS: Record<AgeStage, { hairstyles: { male: readonly string[]; female: readonly string[] }; outfits: readonly string[]; facialHair: readonly string[] }> = {
${rows.join('\n')}
};
`;
  return { options, availability };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { options, availability } = await buildTables();
  await writeFile(path.join(root, 'src', 'portraits', 'options.ts'), options);
  await writeFile(path.join(root, 'src', 'portraits', 'availability.ts'), availability);
  console.log('Wrote src/portraits/options.ts and availability.ts');
}
